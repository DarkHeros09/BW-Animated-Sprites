// indexFile is the pack index the mod loads.
type indexFile struct {
	Source  Source
	Entries map[int]*Entry
}

// lua writes the index as a Lua table literal, sorted by dex so two builds of
// the same dump are byte-identical.
func (f *indexFile) lua() string {
	var b strings.Builder
	b.WriteString("-- Generated by bwsprites; do not edit by hand.\n")
	fmt.Fprintf(&b, "-- Source: %s, game code %s, %s\n", f.Source.Name, f.Source.Code, f.Source.Digest)
	b.WriteString("-- Geometry: native cells. The cell is the animation's own union, so no view is\n")
	b.WriteString("-- resampled: nothing is enlarged and nothing is reduced, and <side>Size is\n")
	fmt.Fprintf(&b, "-- whatever the art needs (64..%d px). The union is centred with its lowest\n", measure.MaxCell)
	b.WriteString("-- ink row on the cell's last row; frames keep their per-frame offset inside\n")
	b.WriteString("-- the union, so motion survives. A front taller than the battle slot is\n")
	b.WriteString("-- top-anchored on row 0 and runs behind the battle menu; the mod shifts wide\n")
	b.WriteString("-- pictures left and keeps them inside the 240 px scene. A tall own back starts\n")
	b.WriteString("-- below the enemy healthbox so its top is never clipped. The mod zeroes the\n")
	b.WriteString("-- per-species y padding so the feet land on the cartridge ground row.\n")
	b.WriteString("-- <side>Dex is the box enclosing every pose; the runtime crops that window at\n")
	b.WriteString("-- 1:1 and the mod centres it in the Pokedex card's picture area, so the dex\n")
	b.WriteString("-- shows the dump's own pixels while it animates. A window larger than the\n")
	b.WriteString("-- area overhangs it rather than being reduced, and the placement is clamped\n")
	b.WriteString("-- to the screen so no pose is cut off. A female battler\n")
	b.WriteString("-- reads <side>Female fields when the dump has that graphic; otherwise it uses\n")
	b.WriteString("-- the male view.\n")
	b.WriteString("-- See docs/MEASUREMENTS.md.\n")
	b.WriteString("return {\n")
	fmt.Fprintf(&b, "  format = %d,\n", Format)
	fmt.Fprintf(&b, "  importer = %s,\n", luaQuote(f.Source.Importer))
	fmt.Fprintf(&b, "  tickRate = %d,\n", TickRate)
	fmt.Fprintf(&b, "  box = %d,\n", measure.HostBox)
	fmt.Fprintf(&b, "  pad = %d,\n", measure.HostPad)
	fmt.Fprintf(&b, "  source = { path = %s, code = %s, name = %s, digest = %s },\n",
		luaQuote(f.Source.Path), luaQuote(f.Source.Code), luaQuote(f.Source.Name), luaQuote(f.Source.Digest))
	b.WriteString("  entries = {\n")
	dexes := make([]int, 0, len(f.Entries))
	for dex := range f.Entries {
		dexes = append(dexes, dex)
	}
	sort.Ints(dexes)
	for _, dex := range dexes {
		entry := f.Entries[dex]
		fmt.Fprintf(&b, "    [%d] = {\n", dex)
		writeView(&b, "front", entry.Front)
		writeView(&b, "back", entry.Back)
		writeView(&b, "frontFemale", entry.FrontFemale)
		writeView(&b, "backFemale", entry.BackFemale)
		b.WriteString("    },\n")
	}
	b.WriteString("  },\n}\n")
	return b.String()
}

// writeView writes one side's fields, skipping a side the pack does not have.
func writeView(b *strings.Builder, side string, view *View) {
	if view == nil {
		return
	}
	fmt.Fprintf(b, "      %s = %s,\n", side, luaQuote(view.Normal))
	if view.Shiny != "" {
		fmt.Fprintf(b, "      %sShiny = %s,\n", side, luaQuote(view.Shiny))
	}
	fmt.Fprintf(b, "      %sFrames = %d,\n", side, view.Frames)
	fmt.Fprintf(b, "      %sSize = %d,\n", side, view.Size)
	fmt.Fprintf(b, "      %sColumns = %d,\n", side, view.Columns)
	fmt.Fprintf(b, "      %sInkH = %d,\n", side, view.InkH)
	fmt.Fprintf(b, "      %sDex = { x = %d, y = %d, w = %d, h = %d },\n",
		side, view.DexX, view.DexY, view.DexW, view.DexH)
	fmt.Fprintf(b, "      %sDurations = %s,\n", side, luaDurations(view.Durations))
	fmt.Fprintf(b, "      %sLoopStart = %d,\n", side, view.LoopStart)
}

// luaDurations writes a frame duration list.
func luaDurations(durations []int) string {
	parts := make([]string, len(durations))
	for i, d := range durations {
		parts[i] = strconv.Itoa(d)
	}
	return "{" + strings.Join(parts, ", ") + "}"
}

// luaQuote quotes s as a Lua string literal.
func luaQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\', '"':
			b.WriteByte('\\')
			b.WriteRune(r)
		case '\n':
			b.WriteString("\\n")
		case '\r':
			b.WriteString("\\r")
		case '\t':
			b.WriteString("\\t")
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, "\\%03d", r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// writeFileAtomic writes data to path through a temporary file in the same
// directory, so a crash cannot leave a half-written file where a complete one
// is expected.
func writeFileAtomic(path string, data []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp*")
	if err != nil {
		return err
	}
	name := tmp.Name()
	defer os.Remove(name)
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(name, path)
}
